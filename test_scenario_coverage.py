# Users per scenario in the fixtures, benign first. Deliberately the real shape
# of a release -- a big benign majority, two thirty-insider scenarios and one
# group of ten -- so that a fixture failure reads like a run failure.
_GROUP_SIZES: dict[int, int] = {0: 60, 1: 30, 2: 30, 3: 10, 4: 30}
_ROWS_PER_USER = 400


def user_table(
    n_scenarios: int, positives_per_user: dict[int, int] | None = None
) -> pd.DataFrame:
    """The one-row-per-user table Stage 4 works on, built by hand.

    Deterministic and tiny: 130 users for three scenarios, 160 for four, so
    every test in this file runs in milliseconds. ``positives_per_user`` lets a
    test choose which scenario is the scarce one.
    """
    positives_per_user = positives_per_user or {1: 2, 2: 4, 3: 6, 4: 8}
    users, scenarios, rows, positives = [], [], [], []
    for scenario in range(0, n_scenarios + 1):
        for i in range(_GROUP_SIZES[scenario]):
            users.append(f"S{scenario}U{i:03d}")
            scenarios.append(scenario)
            rows.append(_ROWS_PER_USER)
            positives.append(0 if scenario == 0 else positives_per_user[scenario])
    return pd.DataFrame(
        {
            SCENARIO_COLUMN: scenarios,
            ROWS_COLUMN: rows,
            POSITIVES_COLUMN: positives,
        },
        index=pd.Index(users, name="user"),
    )


def split_report(table: pd.DataFrame) -> str:
    """The whole Stage 4 report for a table, exactly as a run would print it."""
    splits = split_all_seeds(table)
    checks = check_splits(splits, table)
    return format_report(build_payload(splits, table), table, checks)


