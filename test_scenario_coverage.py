"""Brief R3 §8 — the fourth scenario appears, and r4.2 did not move.

Four places in this project hard-typed ``(1, 2, 3)``. Three of them printed a
short report; the fourth, ``modeling.runner.summarise``, re-aggregated
per-scenario recall on its way into ``outputs/model_*_metrics.json`` and
**dropped scenario 4 without saying so**. On r5.2 that is 56% of the release's
positive rows, missing from a block that still looked complete because it had
three tidy entries in it.

Two properties are asserted here, and they are the whole point:

**Under r4.2 nothing changed.** ``config.SCENARIOS`` *is* ``(1, 2, 3)`` on
r4.2, so every corrected site must produce byte-identical output to the code
that came before it. The split report is pinned against a literal captured from
the pre-change code, and the aggregation against a verbatim copy of the old
loop, which is kept in this file for exactly that purpose. This is what
licenses touching ``modeling/runner.py`` at all.

**With four scenarios the fourth is there.** Through the split report, through
the aggregation, and through the figure's data preparation.

The one assertion that would have caught the original bug is
:func:`test_the_split_columns_sum_to_the_user_total`: the per-scenario columns
of the split table must add up to the user count printed beside them. They did
not, and the report showed 1,200 users on a row summing to 1,182.

**Why this file is at the project root** rather than beside each package: the
frozen-results fingerprint is ``python -m pytest evaluation/ modeling/ -q``
reporting exactly **101 passed**. Tests added inside those two packages would
move that number, and a moved fingerprint is indistinguishable from a broken
one at a glance.

Run it with::

    python -m pytest test_scenario_coverage.py -q
"""

