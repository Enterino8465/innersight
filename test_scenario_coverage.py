def aggregate_per_scenario_as_of_2026_08_21(
    evaluations: Sequence[Evaluation],
) -> dict[str, Any]:
    """The pre-R3 body of ``modeling.runner.summarise``'s per-scenario loop.

    Kept verbatim, hardcoded tuple and all, so that "the new code agrees with
    the old code on r4.2" is a test rather than a claim. Do not fix this
    function. It is a fossil, and its bug is the point of it.
    """
    from modeling.metrics import aggregate

    per_scenario: dict[str, Any] = {}
    for scenario in (1, 2, 3):
        hits, total, rates = 0, 0, []
        for evaluation in evaluations:
            for entry in evaluation.per_scenario:
                if entry.scenario == scenario:
                    hits += entry.hits
                    total += entry.total
                    if entry.recall is not None:
                        rates.append(entry.recall)
        per_scenario[str(scenario)] = {
            "hits_summed": hits,
            "attack_days_summed": total,
            "pooled_recall": hits / total if total else None,
            "recall_across_seeds": aggregate(rates),
        }
    return per_scenario


def evaluations_over(
    per_seed: Sequence[dict[int, tuple[int, int]]],
) -> list[Evaluation]:
    """One real ``Evaluation`` per seed, carrying the given scenario counts.

    Real ``Evaluation`` objects rather than stubs, so that if the aggregation
    ever starts reading a second field this test keeps being valid. Everything
    except ``per_scenario`` is filler and is never looked at.
    """
    filler = PredictionStats(
        minimum=0.0, maximum=1.0, mean=0.5, std=0.1, distinct=99, n_rows=100
    )
    return [
        Evaluation(
            auprc=0.0,
            random_baseline=0.0,
            auroc=None,
            precision_at_k={},
            stats=filler,
            n_rows=100,
            n_positives=1,
            per_scenario=tuple(
                ScenarioRecall(scenario=scenario, hits=hits, total=total)
                for scenario, (hits, total) in sorted(seed.items())
            ),
        )
        for seed in per_seed
    ]


def _comparable(payload: dict[str, Any]) -> str:
    """JSON with sorted keys, so that NaN == NaN and dict order cannot lie."""
    return json.dumps(payload, sort_keys=True)


def test_the_aggregation_matches_the_old_code_on_three_scenarios() -> None:
    """§8.2 for ``modeling/runner.py``, and the licence to touch that file.

    Swept over 200 randomly generated seed-sets rather than one example: the
    change is in a loop, and a single case can agree by luck. The generator is
    seeded, so a failure here is reproducible.
    """
    rng = np.random.default_rng(20260821)
    for _ in range(200):
        per_seed = [
            {
                scenario: (
                    int(hits := rng.integers(0, 8)),
                    int(hits + rng.integers(0, 5)),
                )
                for scenario in (1, 2, 3)
            }
            for _ in range(int(rng.integers(1, 4)))
        ]
        evaluations = evaluations_over(per_seed)
        assert _comparable(
            aggregate_per_scenario(evaluations, scenarios=(1, 2, 3))
        ) == _comparable(aggregate_per_scenario_as_of_2026_08_21(evaluations))


def test_a_scenario_with_no_attack_days_is_present_and_not_zero() -> None:
    """Absent and "recall 0.0" are different facts. The old code agreed."""
    evaluations = evaluations_over([{1: (0, 0), 2: (3, 4), 3: (0, 0)}])
    aggregated = aggregate_per_scenario(evaluations, scenarios=(1, 2, 3))
    assert set(aggregated) == {"1", "2", "3"}
    assert aggregated["1"]["pooled_recall"] is None
    assert aggregated["1"]["attack_days_summed"] == 0
    assert _comparable(aggregated) == _comparable(
        aggregate_per_scenario_as_of_2026_08_21(evaluations)
    )


